<h2>Estructuras repetitivas de JAVA</h2>
<p>1. FOR
Se utiliza cuando conocemos la cantidad de veces que queremos repetir una instrucción. Permite controlar la inicialización, 
condición y actualización de una variable.
2. WHILE
Permite repetir un bloque de instrucciones mientras una condición sea verdadera. Primero evalúa la condición y después 
ejecuta las instrucciones.
3. DO WHILE
Permite repetir un bloque de instrucciones mientras una condición sea verdadera. Primero ejecuta las instrucciones y 
después evalúa la condición, por lo que se ejecuta al menos una vez.</p>
<h2>Estructuras y métodos de JAVA</h2>
<p>1. Atributos
Los atributos son variables que se declaran dentro de una clase y representan las características o propiedades de un objeto. Permiten almacenar información sobre el estado de un objeto.

Tipos de atributos:

Públicos (public): pueden accederse desde otras clases.

Privados (private): solo pueden accederse directamente desde la misma clase.

Protegidos (protected): pueden accederse desde la misma clase, el mismo paquete y sus subclases.

Estáticos (static): pertenecen a la clase y son compartidos por sus objetos.

2. Métodos
Los métodos son bloques de código que realizan una tarea específica dentro de una clase. Permiten definir el comportamiento de los objetos y reutilizar instrucciones.

Tipos de métodos:

Métodos con retorno: devuelven un valor mediante return.

Métodos void: realizan una acción sin devolver un valor.

Métodos estáticos (static): pertenecen a la clase y no necesitan crear un objeto para utilizarse.

Métodos de instancia: pertenecen a los objetos de una clase.

Métodos constructores: se utilizan para inicializar los objetos cuando son creados.</p>
<h2>Herencia de JAVA</h2>
<p>La herencia en Java es un concepto de la programación orientada a objetos que permite que una clase (hija o subclase) adquiera los atributos y métodos de otra clase (padre o superclase).

Su principal objetivo es reutilizar código, evitar repetir instrucciones y facilitar la organización de los programas.

1. Tipos de herencia
Herencia simple: una clase hija hereda de una sola clase padre.

Herencia multinivel: una clase hereda de otra que, a su vez, hereda de una tercera.

Herencia jerárquica: varias clases hijas heredan de una misma clase padre.

Herencia múltiple: una clase hereda de varias clases. Java no permite herencia múltiple entre clases, pero permite implementar varias interfaces.

2. Palabra clave EXTENDS
La palabra extends se utiliza para indicar que una clase hereda de otra.

3. Palabra clave SUPER
La palabra super permite acceder a los atributos y métodos de la clase padre y llamar a su constructor.

4. Características de la herencia
Permite reutilizar código.

Facilita la organización de las clases.

Favorece el mantenimiento de los programas.

Permite ampliar las funcionalidades de una clase.

Facilita la aplicación del polimorfismo.

5. Ventajas de la herencia
Reduce la duplicación de código.

Facilita la creación de nuevas clases.

Mejora la organización del programa.

Permite aprovechar funcionalidades existentes.</p>
