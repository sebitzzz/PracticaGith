    <h1>RESUMEN DE JAVA</h1>
    <p>Java es un lenguaje de programación de propósito general, orientado a objetos y multiplataforma creado en 1995 por Sun Microsystems (actualmente propiedad de Oracle). Es uno de los lenguajes más utilizados en el mundo para el desarrollo de software empresarial, aplicaciones móviles y sistemas de gran escala.</p><br>
<h1>Sintaxis de java</h1>
<p>La sintaxis de Java deriva en gran medida de C y C++, pero con reglas más estrictas para evitar errores comunes. Es sensible a mayúsculas y minúsculas (case-sensitive), cada instrucción termina en punto y coma (;) y los bloques de código se agrupan entre llaves ({}).</p><br>
<p>Todo archivo .java debe contener una clase pública con el mismo nombre que el archivo (por ejemplo, Programa.java).</p>
<h1>Estructuras Repetitivas</h1>
<p>Las estructuras repetitivas permiten ejecutar un bloque de código varias veces mientras se cumpla una condición. Las principales estructuras repetitivas en Java son:</p><br>
<h2>Bucle for (Para):</h2>
<p>El bucle for se utiliza cuando se conoce de antemano el número de iteraciones. Su sintaxis es: for (inicialización; condición; incremento) { // código a ejecutar }.</p><br>
<h2>Bucle for-each (Para cada):</h2>
<p>El bucle for-each se utiliza para iterar sobre elementos de una colección o array. Su sintaxis es: for (tipo variable : colección) { // código a ejecutar }.</p><br>
<h2>Bucle while (Mientras):</h2>
<p>El bucle while ejecuta un bloque de código mientras la condición sea verdadera. Su sintaxis es: while (condición) { // código a ejecutar }.</p>
<h1>POO (Atributos y Métodos).</h1>
<p>En la Programación Orientada a Objetos (POO) en Java, una clase es el molde o plano, y un objeto es la instancia concreta creada a partir de ese molde. Los atributos y los métodos son los dos componentes fundamentales que definen a toda clase.</p><br>
<h1>Herencia</h1>
<p>La herencia es un concepto en la Programación Orientada a Objetos que permite crear nuevas clases basadas en clases existentes. La clase que se hereda se llama clase padre o superclase, y la clase que hereda se llama clase hija o subclase.</p>
