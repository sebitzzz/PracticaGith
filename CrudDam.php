    <h1>Archico conjunto sobre CRUD</h1>
    <h2>INTRODUCCIÓN</h2>
    <P>CRUD es el acrónimo que representa las cuatro operaciones básicas necesarias para gestionar la información en cualquier sistema de almacenamiento persistente. Estas iniciales corresponden a las palabras en inglés Create, Read, Update y Delete, las cuales constituyen el ciclo de vida completo de un dato dentro de una aplicación.</P>
    <h2>CREATE</h2>
    <p>La operación Create (Crear) es el primer paso del ciclo de vida de cualquier dato y se encarga de generar y guardar un nuevo registro en una base de datos o sistema. Sin esta función, una aplicación estaría vacía y no podría almacenar información nueva generada por los usuarios o por el mismo sistema.</p>
